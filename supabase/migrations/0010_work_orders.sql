-- ─────────────────────────────────────────────
-- ORDER NUMBER SEQUENCE TABLE
-- One row per (organization, branch, year) — for safe concurrent number generation
-- ─────────────────────────────────────────────
create table public.order_number_sequences (
  organization_id uuid not null references public.organizations(id) on delete restrict,
  branch_code     text not null,
  year            int  not null,
  last_sequence   int  not null default 0,
  primary key (organization_id, branch_code, year)
);

comment on table public.order_number_sequences is 'Counter table for generating unique, readable order numbers. Use generate_order_number() RPC only.';

-- ─────────────────────────────────────────────
-- RPC: Generate order number (concurrency-safe)
-- Uses SELECT FOR UPDATE to prevent race conditions
-- Format: ESC-2026-000001
-- ─────────────────────────────────────────────
create or replace function public.generate_order_number(
  p_organization_id uuid,
  p_branch_code     text,
  p_year            int default extract(year from now())::int
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_next_seq int;
begin
  -- Upsert sequence row and lock it for this transaction
  insert into public.order_number_sequences (organization_id, branch_code, year, last_sequence)
  values (p_organization_id, p_branch_code, p_year, 0)
  on conflict (organization_id, branch_code, year) do nothing;

  -- Lock the row and increment atomically
  update public.order_number_sequences
  set last_sequence = last_sequence + 1
  where organization_id = p_organization_id
    and branch_code = p_branch_code
    and year = p_year
  returning last_sequence into v_next_seq;

  -- Format: ESC-2026-000001
  return p_branch_code || '-' || p_year || '-' || lpad(v_next_seq::text, 6, '0');
end;
$$;

