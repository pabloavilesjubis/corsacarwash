-- ─────────────────────────────────────────────
-- TRIGGER: Auto-record status changes
-- ─────────────────────────────────────────────
create or replace function public.record_order_status_change()
returns trigger language plpgsql as $$
begin
  if new.status <> old.status then
    insert into public.work_order_status_history (
      work_order_id, previous_status, new_status, changed_by, source
    ) values (
      new.id, old.status, new.status, new.updated_by, 'manual'
    );

    -- Update relevant timestamp
    case new.status
      when 'washing'  then new.started_at = coalesce(new.started_at, now());
      when 'ready'    then new.ready_at = now();
      when 'paid'     then null;  -- set by payment RPC
      when 'delivered' then new.delivered_at = now();
      when 'cancelled' then new.cancelled_at = now();
      else null;
    end case;
  end if;
  return new;
end;
$$;

create trigger work_order_status_change
  before update on public.work_orders
  for each row execute function public.record_order_status_change();

